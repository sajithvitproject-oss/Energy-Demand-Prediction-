# STEP 2 — Parse AEMO Operational Demand file correctly

def parse_aemo_operational_demand_zip(zip_path):
    records = []

    with zipfile.ZipFile(zip_path) as zf:
        csv_members = [
            name for name in zf.namelist()
            if name.lower().endswith(".csv")
        ]

        if not csv_members:
            raise ValueError("No CSV file found inside the AEMO ZIP.")

        for member in csv_members:

            with zf.open(member) as f:
                text = f.read().decode("utf-8-sig", errors="replace")

            rows = csv.reader(io.StringIO(text))

            for row in rows:

                if not row:
                    continue

                # Data rows in this AEMO file begin with D
                if row[0].strip() == "D":

                    # Actual structure:
                    # 0 = D
                    # 1 = OPERATIONAL_DEMAND
                    # 2 = ACTUAL5M
                    # 3 = version
                    # 4 = REGIONID
                    # 5 = INTERVAL_DATETIME
                    # 6 = OPERATIONAL_DEMAND value

                    if len(row) >= 7:
                        records.append({
                            "timestamp": row[5].strip(),
                            "region": row[4].strip(),
                            "demand_mw": row[6].strip()
                        })

    df = pd.DataFrame(records)

    df["timestamp"] = pd.to_datetime(
        df["timestamp"],
        errors="coerce"
    )

    df["demand_mw"] = pd.to_numeric(
        df["demand_mw"],
        errors="coerce"
    )

    df = df.dropna(
        subset=["timestamp", "region", "demand_mw"]
    )

    return df


